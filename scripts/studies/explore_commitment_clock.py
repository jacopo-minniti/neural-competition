"""Race between task-induced polarization and endogenous main-effect fitting.

Compare a population clock with the clock generated by the same finite set
of independent forced neuron trajectories. Forecasts precede actual training.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from explore_polarization_width_law import labels
from explore_stable_distinctions import task
from explore_transported_gates import initialize, losses, train

ROOT=Path(__file__).resolve().parents[2]/'docs/theory'
CASES=[('base',.1,.002),('rare',.02,.002),('rarer',.005,.002),
       ('medium_init',.1,.02),('ordinary_init',.1,.2)]


def forced_step(w,a,x,p,y):
    h=((w@x.T>0)*(p*y))@x
    da=np.sum(w*h,axis=-1)
    dw=a[...,None]*h
    return w+.02*dw,a+.02*da


def cost(family,q):
    pos=np.any(family==1,axis=-1)
    neg=np.any(family==-1,axis=-1)
    return np.where(pos&neg,0,np.where(pos|neg,q*(1-q),2+6*q))


def forecast():
    rows,raw=[],{}
    for name,q,scale in CASES:
        x,p,y=task(1,0.,q)
        z=x[:,1]
        target_main=p@(z*y)
        initial=initialize(281399,256,12)
        w,a=initial[0]*scale/.2,initial[1]*scale/.2
        bank=initialize(281310,1,16384)
        bw,ba=bank[0][0]*scale/.2,bank[1][0]*scale/.2
        predicted={m:np.full(256,np.nan) for m in (4,6,8,12)}
        times={m:np.full(256,np.nan) for m in predicted}
        population_time=None
        for step in range(3201):
            family=labels(w,a,x)
            contribution=a*np.sum(np.maximum(w@x.T,0)*(p*z),axis=-1)
            for m in predicted:
                crossing=contribution[:,:m].mean(1)>=target_main
                all_dead=np.all(family[:,:m]==0,axis=1)
                new=np.isnan(predicted[m])&(crossing|all_dead)
                predicted[m][new]=cost(family[new,:m],q)
                times[m][new]=np.where(all_dead[new],np.inf,step*.02)
            if population_time is None:
                bank_progress=np.mean(ba*np.sum(np.maximum(bw@x.T,0)*(p*z),axis=1))
                if bank_progress>=target_main:
                    population_time=step*.02
                    d=float(np.mean(labels(bw,ba,x)==0))
                    for m in predicted:
                        raw[f'{name}_m{m}_population_prediction']=cost(family[:,:m],q)
            if population_time is not None and all(np.all(np.isfinite(v)) for v in predicted.values()):
                break
            w,a=forced_step(w,a,x,p,y)
            bw,ba=forced_step(bw,ba,x,p,y)
        assert population_time is not None
        for m in predicted:
            raw[f'{name}_m{m}_prediction']=predicted[m]
            raw[f'{name}_m{m}_clock']=times[m]
            law=2*q*(1-q)*((1+d)/2)**m+(2+6*q-2*q*(1-q))*d**m
            row=dict(case=name,q=q,scale=scale,width=m,population_clock=population_time,
                death_at_clock=d,population_law=float(law),
                population_realized=float(raw[f'{name}_m{m}_population_prediction'].mean()),
                endogenous_realized=float(np.nanmean(predicted[m])),
                unresolved_clocks=int(np.sum(np.isnan(predicted[m]))),
                finite_clock_mean=float(times[m][np.isfinite(times[m])].mean()))
            rows.append(row)
        print(json.dumps(rows[-4:]),flush=True)
    result=dict(protocol=dict(seed=281399,seeds=256,widths=[4,6,8,12],endpoint=2000,
        bank=16384,forced_dt=.02,training_dt=.05),forecasts=rows,
        status='Saved before held-out ordinary training continuations.')
    (ROOT/'commitment_clock_forecasts.json').write_text(json.dumps(result,indent=2)+'\n')
    np.savez_compressed(ROOT/'commitment_clock_predictions.npz',**raw)


def validate():
    result=json.loads((ROOT/'commitment_clock_forecasts.json').read_text())
    raw=np.load(ROOT/'commitment_clock_predictions.npz')
    rows,endpoints=[],{}
    for name,q,scale in CASES:
        x,p,y=task(1,0.,q)
        initial=initialize(281399,256,12)
        for m in (4,6,8,12):
            state=(initial[0][:,:m]*scale/.2,initial[1][:,:m]*scale/.2,initial[2].copy())
            end=train(state,x,p,y,2000)
            loss=losses(end,x,p,y)
            pred=raw[f'{name}_m{m}_prediction']
            pop=raw[f'{name}_m{m}_population_prediction']
            resolved=np.isfinite(pred)
            row=dict(case=name,width=m,mean_loss=float(loss.mean()),se=float(loss.std(ddof=1)/np.sqrt(len(loss))),
                endogenous_mean=float(np.nanmean(pred)),population_mean=float(pop.mean()),
                unresolved_clocks=int(np.sum(~resolved)),
                unresolved_actual_losses=loss[~resolved].tolist(),
                endogenous_mae=float(abs(pred[resolved]-loss[resolved]).mean()),population_mae=float(abs(pop-loss).mean()),
                false_failures=int(np.sum((pred>1e-6)&(loss<1e-6))),
                missed_failures=int(np.sum((pred<1e-6)&(loss>1e-6))))
            rows.append(row)
            endpoints[f'{name}_m{m}_loss']=loss
            print(json.dumps(row),flush=True)
            (ROOT/'commitment_clock_validation.json').write_text(json.dumps(dict(**result,validation=rows),indent=2)+'\n')
            np.savez_compressed(ROOT/'commitment_clock_validation.npz',**endpoints)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('phase',choices=['forecast','validate'])
    args=parser.parse_args()
    forecast() if args.phase=='forecast' else validate()
